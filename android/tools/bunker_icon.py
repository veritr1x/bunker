#!/usr/bin/env python3
"""The Bunker emblem: the command-room floor emblem of the YoRHa Bunker,
simplified — an upright blade, two blades sweeping down and out, a hollow
diamond at the centre and a small diamond below — drawn like the game's own
header icons (cream strokes on a dark diamond plate).

Writes android/app/src/main/cpp/bunker_icon.h, the PNG the in-game Bunker
button shows (bunker_button.c). The plate and colours were matched on a
device against the game's Notices icon.

    python3 android/tools/bunker_icon.py
"""
from pathlib import Path
import io

root = Path(__file__).resolve().parents[2]
HEADER = root / "android/app/src/main/cpp/bunker_icon.h"

SIZE = 128
PLATE = (36, 28, 19, 196)   # the game's plate: dark brown, a little see-through
CREAM = (231, 224, 205, 255)


def draw(size=SIZE, plate=PLATE, cream=CREAM):
    """The emblem as an RGBA image; plate None leaves it out."""
    from PIL import Image, ImageDraw
    big = size * 4  # drawn large, then scaled down for smooth edges
    k = big / 100
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    pen = ImageDraw.Draw(image)
    at = lambda points: [(x * k, y * k) for x, y in points]
    # The glyph's points in a 0..100 square, scaled 1.25 about (50, 49).
    glyph = lambda points: at([(50 + (x - 50) * 1.25, 49 + (y - 49) * 1.25) for x, y in points])
    stroke = int(7 * k)
    if plate:
        pen.polygon(at([(50, 0.5), (99.5, 50), (50, 99.5), (0.5, 50)]), fill=plate)
    pen.polygon(glyph([(50, 25), (54.5, 38), (45.5, 38)]), fill=cream)              # upright blade
    pen.line(glyph([(46.5, 49), (33, 60)]), fill=cream, width=stroke)              # blades sweeping out
    pen.line(glyph([(53.5, 49), (67, 60)]), fill=cream, width=stroke)
    pen.line(glyph([(50, 38.5), (57, 45.5), (50, 52.5), (43, 45.5), (50, 38.5)]),  # hollow diamond
             fill=cream, width=stroke, joint="curve")
    pen.polygon(glyph([(50, 57), (54, 61), (50, 65), (46, 61)]), fill=cream)       # accent
    return image.resize((size, size), Image.LANCZOS)


def png(image):
    out = io.BytesIO()
    image.save(out, "PNG", optimize=True)
    return out.getvalue()


def write_header(path=HEADER):
    data = png(draw())
    lines = [", ".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    Path(path).write_text(
        "// Generated by android/tools/bunker_icon.py: the Bunker emblem (128x128 PNG).\n"
        "#pragma once\n\n"
        f"static const unsigned int kBunkerIconPngSize = {len(data)};\n"
        "static const unsigned char kBunkerIconPng[] = {\n    " + ",\n    ".join(lines) + "};\n")


if __name__ == "__main__":
    write_header()
    print(HEADER)
