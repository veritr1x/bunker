"""Compare indexed FMLA result/source bits, FPSR and NZCV with actual ARM64."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from fp_fmla_cases import generate
from test_fastaes import build_reference
HERE=Path(__file__).resolve().parent


def digest(path):
    value=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda:stream.read(1024*1024),b''):value.update(block)
    return value.hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-root',type=Path,required=True)
    parser.add_argument('--lift',type=Path)
    parser.add_argument('--remill',type=Path,default=HERE.parent/'work/remill-src')
    parser.add_argument('--windows',action='store_true')
    parser.add_argument('--reference-only',action='store_true')
    parser.add_argument('--reference-file',type=Path,help='Reuse an exact hash/source-verified ARM64 oracle generated by this runner')
    parser.add_argument('--record-directory',type=Path,help='Store large binary records on a native Linux filesystem for faster I/O')
    args=parser.parse_args();out=HERE.parent/f'work/fp-fmla-{"windows" if args.windows else "linux"}';out.mkdir(exist_ok=True,parents=True)
    record_directory=args.record_directory or out;record_directory.mkdir(exist_ok=True,parents=True)
    cases=generate();source=out/'fixture.S';lines=['.text'];declarations=[];records=0
    for name,(body,width,exhaustive,d,n,m,lanes,index) in cases.items():
        lines += [f'.global {name}',f'.type {name}, %function',f'{name}:','.cfi_startproc',*('    '+op for op in body),'.cfi_endproc',f'.size {name}, .-{name}']
        declarations += [f'CASE({name},{width},{int(exhaustive)},{d},{n},{m},{lanes},{index})']
        records += 32*((8000 if exhaustive else 400)+1024+((254 if width==32 else 2046)*8 if exhaustive else 64))
    source.write_text('\n'.join(lines)+'\n');(out/'fp_fmla_generated.h').write_text('\n'.join(declarations)+'\n')
    reference_key={str(p.name):digest(p) for p in [source,out/'fp_fmla_generated.h',HERE/'fp_fmla_driver.h',HERE/'fp_fmla_ref.c']}
    reference_key['qemu_sha256']=digest(args.reference_root/'usr/bin/qemu-aarch64-static')
    if args.reference_file:
        expected=args.reference_file.resolve();metadata=json.loads(expected.with_suffix('.provenance.json').read_text())
        if metadata['key']!=reference_key or metadata['sha256']!=digest(expected):raise RuntimeError('FMLA oracle source/binary hash mismatch')
    else:
        reference=out/'reference';build_reference('clang-18',args.reference_root,[HERE/'fp_fmla_ref.c',source],reference,[HERE,out])
        expected=record_directory/'reference.bin'
        with expected.open('wb') as stream:subprocess.run([str(args.reference_root/'usr/bin/qemu-aarch64-static'),str(reference)],check=True,stdout=stream)
        expected.with_suffix('.provenance.json').write_text(json.dumps({'key':reference_key,'sha256':digest(expected)},indent=2)+'\n')
    assert expected.stat().st_size==records*64
    print(f'ARM64 FMLA oracle: {len(cases)} variants, {records:,} records',flush=True)
    if args.reference_only:return
    if not args.lift:parser.error('--lift required unless --reference-only')
    image=out/'fixture.so';subprocess.run(['clang-18','--target=aarch64-linux-gnu','-fuse-ld=lld','-shared','-nostdlib','-fPIC',str(source),'-o',str(image)],check=True)
    subprocess.run([sys.executable,str(HERE/'compile.py'),str(image),'--out',str(out/'lifted'),'--lift',str(args.lift),'--cxx','clang++-18','--target','x86_64-w64-windows-gnu' if args.windows else'x86_64-linux-gnu','--base','0x5d000000'],check=True)
    manifest=json.loads((out/'lifted/manifest.json').read_text());assert not manifest['unsupported_traces'] and not manifest['unresolved_direct_targets']
    def hp(path):return subprocess.check_output(['wslpath','-m',str(Path(path).resolve())],text=True).strip() if args.windows else str(Path(path).resolve())
    cc='/mnt/c/mingw64/bin/gcc.exe'if args.windows else'clang-18';cxx='/mnt/c/mingw64/bin/g++.exe'if args.windows else'clang++-18'
    loader=out/'elfload.o';subprocess.run([cc,'-O2','-c',hp(HERE.parent/'fastaes/elfload.c'),'-o',hp(loader)],check=True)
    binary=out/('test.exe'if args.windows else'test')
    command=[cxx,'-std=c++17','-O2','-DADDRESS_SIZE_BITS=64','-I'+hp(args.remill/'include'),'-I'+hp(HERE),'-I'+hp(out),'-I'+hp(out/'lifted'),f'-DFMLA_IMAGE="{hp(image)}"',hp(HERE/'fp_fmla_test.cpp'),hp(HERE/'runtime.cpp'),hp(loader),*map(hp,manifest['objects']),'-latomic','-o',hp(binary)]
    if args.windows:command[1:1]=['-static','-pthread']
    subprocess.run(command,check=True)
    actual=record_directory/('actual-windows.bin' if args.windows else 'actual-linux.bin')
    with actual.open('wb') as stream:subprocess.run([str(binary)],stdout=stream,check=True)
    with expected.open('rb') as ref,actual.open('rb') as got:
        offset=0
        while True:
            a=ref.read(64*16384);b=got.read(64*16384)
            if a!=b:
                for at in range(0,max(len(a),len(b)),64):
                    if a[at:at+64]!=b[at:at+64]:raise RuntimeError(f'FMLA mismatch record{offset//64+at//64}: expected{a[at:at+64].hex()} actual{b[at:at+64].hex()}')
            if not a:break
            offset+=len(a)
    (out/'acceptance.json').write_text(json.dumps({'passed':True,'variants':len(cases),'records':records,'record_bytes':64,'toolchain':manifest['toolchain'],'reference_sha256':digest(expected),'actual_sha256':digest(actual),'sources':{str(p):digest(p) for p in [HERE/'fp_fmla_cases.py',HERE/'fp_fmla_driver.h',HERE/'fp_fmla_ref.c',HERE/'fp_fmla_test.cpp',HERE/'test_fp_fmla.py']}},indent=2)+'\n')
    print(f'Indexed FMLA PASS: {records:,} exact result/source/FPSR/NZCV records',flush=True)


if __name__=='__main__':main()
